local require = require("cmdline.util.lazy")

local Api = require("cmdline.api")
local Config = require("cmdline.config")

local M = {}

M.api = Api

---@param opts? NoiceConfig
function M.setup(opts)
  if vim.fn.has("nvim-0.10") ~= 1 then
    return vim.notify("cmdline.nvim needs Neovim >= 0.10", vim.log.levels.ERROR)
  end
  if not pcall(_G.require, "nui.object") then
    return vim.notify("cmdline.nvim needs nui.nvim (MunifTanjim/nui.nvim)", vim.log.levels.ERROR)
  end

  local function load()
    require("cmdline.util").try(function()
      require("cmdline.config").setup(opts)
      require("cmdline.commands").setup()
      require("cmdline.message.router").setup()
      M.enable()
    end)
  end

  if vim.v.vim_did_enter == 0 then
    -- Schedule loading after VimEnter. Get the UI up and running first.
    vim.api.nvim_create_autocmd("VimEnter", {
      once = true,
      callback = load,
    })
  else
    -- Schedule on the event loop
    vim.schedule(load)
  end
end

function M.disable()
  Config._running = false
  require("cmdline.message.router").disable()
  require("cmdline.ui").disable()
  require("cmdline.util.hacks").disable()
  require("cmdline.ui2").restore()
end

M.deactivate = M.disable

function M.cmd(name)
  require("cmdline.commands").cmd(name)
end

function M.enable()
  vim.api.nvim_create_autocmd("VimLeavePre", {
    group = vim.api.nvim_create_augroup("CmdlineVimLeavePre", { clear = true }),
    callback = function()
      if Config.is_running() then
        pcall(M.disable)
      end
    end,
  })
  Config._running = true
  require("cmdline.ui2").setup(Config.options.ui2)
  require("cmdline.util.hacks").enable()
  require("cmdline.ui").enable()
  require("cmdline.message.router").enable()
end

-- Redirect any messages generated by a command or function
---@param cmd string|fun() command or function to execute
---@param routes? NoiceRouteConfig[] custom routes. Defaults to `config.redirect`
function M.redirect(cmd, routes)
  return require("cmdline.message.router").redirect(cmd, routes)
end

return M
